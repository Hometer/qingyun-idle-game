// 隔离合成档，只调用真实引擎，不写玩家 IndexedDB、不调用模型。
import * as e from '../../../frontend/src/engine/engine';
import { CONFIG } from '../../../frontend/src/engine/config';
const T = new Date(2026,9,1,10).getTime();
const DAY = 86400000;
const brief = (r: any) => ({ok:r.ok, reason:r.reason});
const out: Record<string, unknown> = {};
const old: any = e.createGame('旧档复查','金','balanced',T);
old.schemaVersion=13;
for (const k of ['itemInstances','lockedAffixes','spiritRoots','legacyRootPending','resonance','meridians','comprehension','marrowHistory']) delete old[k];
const migrated=e.migrateSave(old);
const freshMigrated=e.migrateSave(e.createGame('新档刷新','金','balanced',T));
out.newGameAfterReload={affixes:Object.values(freshMigrated.itemInstances).map(i=>i.affixes),roundtrip:brief(e.importSave(e.exportSave(freshMigrated)))};
out.legacyEquipment={beforeInventory:old.inventory,afterInventory:migrated.inventory,affixes:Object.values(migrated.itemInstances).map(i=>i.affixes),roundtrip:brief(e.importSave(e.exportSave(migrated)))};
out.legacyRoots={pending:migrated.legacyRootPending,beforeResonance:brief(e.setResonance(migrated,T,'金')),freeSettle:brief(e.settleRoots(migrated,T,['水']))};
let poor=e.createGame('缺资源','金','balanced',T);
poor.maps.map_qingyun.node_wolf.cleared=true;
poor=e.settle(poor,T);
const craft=poor.commission.candidates.find(c=>c.kind==='craft')!;
const acc=e.acceptCommission(poor,T,craft.id);
const action=craft.action==='upgradeBuilding' ? e.upgradeBuilding(acc.state!,T,craft.actionParam as any) : null;
out.resourceCandidate={candidate:craft.title,param:craft.actionParam,resources:poor.resources,accepted:brief(acc),execute:action&&brief(action)};
let rich=e.createGame('日限制','金','balanced',T);
for(const k of Object.keys(rich.resources))(rich.resources as any)[k]=1e8;
rich.realm='zhuji1';rich.maps.map_qingyun.node_wolf.cleared=true;
rich=e.settle(rich,T+DAY);
const c=rich.commission.candidates.find(c=>c.kind==='battle')!;
const a=e.acceptCommission(rich,T+DAY,c.id);if(!a.ok)throw Error(a.reason);
const b=e.fightNode(a.state!,T+DAY,c.mapId!,c.nodeId!,'challenge');
const claim=e.claimCommission(b.state,T+DAY,'b');if(!claim.ok)throw Error(claim.reason);
const first=e.fightNode(claim.state!,T+DAY,'map_qingyun','node_side_1');
const c2=first.state.commission.candidates.find(c=>c.kind==='battle');
out.dailyLimit={firstWon:first.won,acceptedDate:first.state.commission.acceptedDate,secondAccept:c2?brief(e.acceptCommission(first.state,T+DAY,c2.id)):null,history:first.state.commission.history.length};
const state=e.createGame('功法矩阵','金','balanced',T);state.realm='hongmeng10';state.library=7;
for(const k of Object.keys(state.resources))(state.resources as any)[k]=1e10;
for(const nodes of Object.values(state.maps)) for(const node of Object.values(nodes)){node.unlocked=true;node.cleared=true;}
state.learnedNewTechs=Object.keys(CONFIG.techniques).filter(k=>!['qingYun','xuanGui','poYue','juYuan'].includes(k)) as any;
const selected=e.setTechnique(state,T,'qingYun');
out.validTechniqueFixture=brief(e.importSave(e.exportSave(selected.state!)));
console.log(JSON.stringify(out,null,2));
